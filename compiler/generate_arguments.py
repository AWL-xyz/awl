#!/usr/bin/env python3
"""Embed the native decimal parser and CLI argument runtime in the compiler."""
import argparse
from pathlib import Path

p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--check', action='store_true')
a = p.parse_args()
root = Path(__file__).resolve().parent / 'native'
expected = '// Generated by compiler/generate_arguments.py from decimal.c and arguments.c.\n'
for name in ('decimal', 'arguments'):
    source = (root / f'{name}.c').read_text()
    tag = name.upper()
    assert f'){tag}"' not in source
    expected += f'constexpr char c_{name}[]=R"{tag}({source}){tag}";\n'
target = root / 'arguments.inc'
if a.check:
    if not target.exists() or target.read_text() != expected:
        raise SystemExit('arguments.inc stale: run compiler/generate_arguments.py')
else:
    target.write_text(expected)
