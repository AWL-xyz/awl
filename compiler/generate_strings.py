#!/usr/bin/env python3
"""Contributor-only embedding of the native immutable-string runtime."""
import argparse
from pathlib import Path
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args()
root=Path(__file__).resolve().parent/'native';source=(root/'strings.c').read_text();assert ')KSTRINGS"' not in source
expected='// Generated by compiler/generate_strings.py from kstrings.c.\nconstexpr char c_strings[]=R"KSTRINGS('+source+')KSTRINGS";\n'
target=root/'strings.inc'
if a.check:
    if not target.exists() or target.read_text()!=expected:raise SystemExit('strings.inc stale: run compiler/generate_strings.py')
else:target.write_text(expected)
