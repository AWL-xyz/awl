#!/usr/bin/env python3
"""Contributor-only deterministic embedding; no installed Python dependency."""
import argparse
from pathlib import Path
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true')
a=parser.parse_args()
p=Path(__file__).resolve().parent/'native'
s=(p/'kplatform.c').read_text()
assert ')KPLATFORM"' not in s
expected='// Generated by compiler/generate_platform.py from kplatform.c.\nconstexpr char c_platform[]=R"KPLATFORM('+s+')KPLATFORM";\n'
if a.check:
    if not (p/'kplatform.inc').exists() or (p/'kplatform.inc').read_text()!=expected:
        raise SystemExit('kplatform.inc stale: run python3 compiler/generate_platform.py')
else:
    (p/'kplatform.inc').write_text(expected)
