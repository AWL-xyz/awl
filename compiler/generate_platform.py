#!/usr/bin/env python3
"""Contributor-only deterministic embedding; no installed Python dependency."""
import argparse
from pathlib import Path

SPECS = [
    ('kplatform.c', 'kplatform.inc', 'c_platform', 'KPLATFORM'),
    ('kwallclock.c', 'kwallclock.inc', 'c_wall_clock', 'KWALLCLOCK'),
]

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
a = parser.parse_args()
p = Path(__file__).resolve().parent / 'native'
for source, target, variable, tag in SPECS:
    s = (p / source).read_text()
    assert ')' + tag + '"' not in s
    expected = ('// Generated by compiler/generate_platform.py from ' + source + '.\n'
                + 'constexpr char ' + variable + '[]=R"' + tag + '(' + s + ')' + tag + '";\n')
    if a.check:
        if not (p / target).is_file() or (p / target).read_text() != expected:
            raise SystemExit(target + ' stale: run python3 compiler/generate_platform.py')
    else:
        (p / target).write_text(expected)
print('embedded platform helpers match reference C templates')
